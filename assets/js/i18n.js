function applyTranslation(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            const value = translations[lang][key];
            // Handle <meta> tags (set content) and normal elements (textContent)
            if (el.tagName === 'META') {
                el.setAttribute('content', value);
            } else if (el.tagName === 'TITLE') {
                document.title = value;
                el.textContent = value;
            } else {
                el.textContent = value;
            }
        }
    });
    // Set document language attribute for accessibility
    try { document.documentElement.lang = lang; } catch (e) {}
    // Update QR alt text if present (site and linktree)
    try {
        var qrSite = document.getElementById('siteQrSite');
        if(qrSite && translations[lang] && translations[lang]['qrcode.site.title']){
            qrSite.alt = translations[lang]['qrcode.site.title'];
        }
        var qrLinktr = document.getElementById('siteQrLinktree');
        if(qrLinktr && translations[lang] && translations[lang]['qrcode.linktree.title']){
            qrLinktr.alt = translations[lang]['qrcode.linktree.title'];
        }
    } catch(e){}
    localStorage.setItem('lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('lang') || 'fr';
    applyTranslation(savedLang);

    // Attach listeners to any element using data-lang="xx"
    document.querySelectorAll('[data-lang]').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = btn.getAttribute('data-lang');
            if (lang) applyTranslation(lang);
        });
    });


    // Attach PDF embed handler (buttons with data-action="embed-pdf")
    document.querySelectorAll('[data-action="embed-pdf"]').forEach(btn => {
        btn.addEventListener('click', () => {
            const pdf = btn.getAttribute('data-pdf');
            const container = document.getElementById('pdfContainer');
            if (container && pdf) {
                const lang = localStorage.getItem('lang') || 'fr';
                const closeText = (translations[lang] && translations[lang]['pdf.close']) ? translations[lang]['pdf.close'] : 'Close PDF';
                container.innerHTML = `<div class="pdf-frame-wrap"><button id="closePdfBtn" class="close-pdf">${closeText}</button><iframe src="${pdf}" style="width:100%;height:600px;border:0"></iframe></div>`;
                container.scrollIntoView({behavior: 'smooth'});
                const closeBtn = document.getElementById('closePdfBtn');
                if (closeBtn) {
                    closeBtn.addEventListener('click', () => {
                        container.innerHTML = '';
                    });
                }
            }
        });
    });

    // Language dropdown toggle (single button)
    const translateBtn = document.getElementById('translateBtn');
    const langMenu = document.getElementById('langMenu');
    if (translateBtn && langMenu) {
        translateBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const isHidden = langMenu.hasAttribute('hidden');
            if (isHidden) {
                langMenu.removeAttribute('hidden');
                translateBtn.setAttribute('aria-expanded', 'true');
            } else {
                langMenu.setAttribute('hidden', '');
                translateBtn.setAttribute('aria-expanded', 'false');
            }
        });

        // Close menu when clicking outside
        document.addEventListener('click', (e) => {
            if (!langMenu.contains(e.target) && e.target !== translateBtn) {
                if (!langMenu.hasAttribute('hidden')) {
                    langMenu.setAttribute('hidden', '');
                    translateBtn.setAttribute('aria-expanded', 'false');
                }
            }
        });

        // Close on Escape
        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape') {
                if (!langMenu.hasAttribute('hidden')) {
                    langMenu.setAttribute('hidden', '');
                    translateBtn.setAttribute('aria-expanded', 'false');
                }
            }
        });

        // Ensure menu closes after selecting a language
        document.querySelectorAll('[data-lang]').forEach(btn => {
            btn.addEventListener('click', () => {
                if (!langMenu.hasAttribute('hidden')) {
                    langMenu.setAttribute('hidden', '');
                    translateBtn.setAttribute('aria-expanded', 'false');
                }
            });
        });
    }
});